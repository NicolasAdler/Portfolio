        function plugin = EQ()
            smoothing_val = 0.9;
            plugin.HI_SMOOTH = ParameterSmoother(plugin.HI_CENTER_FREQ, smoothing_val);
            plugin.HI_GAIN_SMOOTH = ParameterSmoother(plugin.HI_GAIN, smoothing_val);
            plugin.LOW_SMOOTH = ParameterSmoother(plugin.LOW_CENTER_FREQ, smoothing_val);
            plugin.LOW_GAIN_SMOOTH = ParameterSmoother(plugin.LOW_GAIN, smoothing_val);
            plugin.BAND_SMOOTH = ParameterSmoother(plugin.BAND_CENTER_FREQ, smoothing_val);
            plugin.BAND_GAIN_SMOOTH = ParameterSmoother(plugin.BAND_GAIN, smoothing_val);
            plugin.Q_SMOOTH = ParameterSmoother(plugin.Q_factor, smoothing_val);
            plugin.DECAY_SMOOTH = ParameterSmoother(plugin.DECAY, smoothing_val);
            plugin.MIX_SMOOTH = ParameterSmoother(plugin.MIX, smoothing_val);
            plugin.compressor = compressor('Threshold', plugin.THRESHOLD,...
                'Ratio', plugin.RATIO, ...
                'AttackTime',plugin.ATTACK/1000,...
                'ReleaseTime',plugin.RELEASE/1000,...
                'MakeUpGainMode','Auto');
            plugin.reverb = reverberator('PreDelay', 0,...
                'WetDryMix', plugin.MIX/100,...
                'DecayFactor', plugin.DECAY);

            plugin.out1 = dsp.AsyncBuffer;
            plugin.out2 = dsp.AsyncBuffer;
            plugin.out3 = dsp.AsyncBuffer;
        end

        function out = process(plugin, in)
            out = coder.nullcopy(zeros(size(in)));
            numChannels = size(in,2);

            reverberator;

            update_HPF(plugin);
            update_LPF(plugin);
            update_BPF(plugin);

            for ch = 1:numChannels

                if strcmp(plugin.BYPASS, 'bypass')
                    out = in;
                return;
                end

                x = in(:,ch);

                
                [x, plugin.filter_HPF.w(:,ch)] = processBiquad(x, plugin.filter_HPF, ch);
                [x, plugin.filter_LPF.w(:,ch)] = processBiquad(x, plugin.filter_LPF, ch);
                [x, plugin.filter_BPF.w(:,ch)] = processBiquad(x, plugin.filter_BPF, ch);


                filtered_signal = x;

                    write(plugin.out1,filtered_signal);
                    out(:, ch) = plugin.compressor(read(plugin.out1));
                    


            end
            if strcmp(plugin.BYPASS, 'bypass')
                out = in;
                return;
            else
                out(:,:) = plugin.reverb(out);
            end
            
        end

