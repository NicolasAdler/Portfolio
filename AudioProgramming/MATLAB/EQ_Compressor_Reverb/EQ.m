        function update_HPF(plugin)

            
            thetaC = (2.0*pi*plugin.HI_SMOOTH.step()) / plugin.fs;
            d  = 1 / plugin.Q_SMOOTH.step();
            %mu = pow(10,plugin.HI_GAIN_SMOOTH.step()/20.0);
            betaTop = (1-((d/2)*sin(thetaC)));
            betaBottom =(1+((d/2)*sin(thetaC)));
            beta = 0.5 * (betaTop/betaBottom);
            gamma = (0.5 + beta)*cos(thetaC);
            plugin.filter_HPF.a0 = (0.5+beta+gamma)/2.0;
            plugin.filter_HPF.a0 = -1.0*(0.5+beta+gamma);
            plugin.filter_HPF.a2 = (0.5+beta+gamma)/2.0;
            %plugin.filter_HPF.b0 = 1 + alpha;
            plugin.filter_HPF.b1 = -2*gamma;
            plugin.filter_HPF.b2 = 2*beta;
            %}

        end


