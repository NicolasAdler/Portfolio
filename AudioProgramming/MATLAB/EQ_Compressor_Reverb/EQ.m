        function update_LPF(plugin)

            thetaC = (2.0*pi*plugin.LOW_SMOOTH.step())/plugin.fs;
            d  = 1 / plugin.Q_SMOOTH.step();
            betaTop = (1-((d/2.0)*sin(thetaC)));
            %mu = pow(10,gainKnobvalue/20.0);
            betaBottom =(1+((d/2.0)*sin(thetaC)));
            beta = 0.5 * (betaTop/betaBottom);
            gamma = (0.5 + beta)*cos(thetaC);
            plugin.filter_LPF.a0 = (0.5+beta-gamma)/2.0;
            plugin.filter_LPF.a1 = (0.5+beta-gamma);
            plugin.filter_LPF.a2 = (0.5+beta-gamma)/2.0;
            %plugin.filter_LPF.b0 = 1 + alpha;
            plugin.filter_LPF.b1 = -2*gamma;
            plugin.filter_LPF.b2 = 2*beta;

        end


