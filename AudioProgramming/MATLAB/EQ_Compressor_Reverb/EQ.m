            plugin.fs = getSampleRate(plugin);
            plugin.fn = plugin.fs / 2;

            plugin.filter_HPF.w = [0 0; 0 0];
            plugin.filter_LPF.w = [0 0; 0 0];
            plugin.filter_BPF.w = [0 0; 0 0];

        end

