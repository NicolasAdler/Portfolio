        function update_BPF(plugin)

            thetaC = (2.0*pi*plugin.BAND_SMOOTH.step())/plugin.fs;
            betaTop = (1.0-tan(thetaC/(2.0*plugin.Q_SMOOTH.step())));
            betaBottom =(1.0+tan(thetaC/(2.0*plugin.Q_SMOOTH.step())));
            beta = 0.5 * (betaTop/betaBottom);
            gamma = (0.5+beta)*cos(thetaC);
            plugin.filter_BPF.a0 = 0.5-beta;
            plugin.filter_BPF.a1 = 0.0;
            plugin.filter_BPF.a2 = -1.0*(0.5-beta);
            plugin.filter_BPF.b1 = -2*gamma;
            plugin.filter_BPF.b2 = 2*beta;

        end

        
        function [y, filt] = processBiquad_Nick(plugin,x, filt, ch)
            wn_1 = filt.w(1, ch);
            wn_2 = filt.w(2, ch);

            numChannels = size(x,2);
            numSamples = size(x,1);

            y = zeros(numSamples, numChannels);

            for n = 1:numSamples
                w = x(n) - (filt.a1 * wn_1) - (filt.a2 * wn_2);
                y(n) = (filt.b0 * w) + (filt.b1 * wn_1) + (filt.b2 * wn_2);
                wn_2 = wn_1;
                wn_1 = w;
            end

            filt.w(1,ch) = wn_1;
            filt.w(2,ch) = wn_2;
        end

